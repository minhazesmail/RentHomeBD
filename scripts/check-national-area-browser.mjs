import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import locations from '../src/lib/bangladesh-locations.json' with { type: 'json' };

const base = process.env.LIVE_SEARCH_QA_URL ?? 'http://localhost:3003';
const out = path.resolve(process.env.LIVE_SEARCH_QA_OUTPUT ?? 'artifacts/live-search');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1338, height: 950 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/rest/v1/rpc/search_available_properties**', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
  await page.goto(`${base}/homes?area=${encodeURIComponent('Teknaf, Cox\'s Bazar')}&tenant=family`, { waitUntil: 'domcontentloaded', timeout: 180000 });
  const filter = page.getByRole('searchbox', { name: 'Filter areas' });
  const select = page.locator('.renter-toolbar-area select');
  await filter.waitFor({ timeout: 90000 });
  await page.waitForFunction(() => !document.querySelector('.renter-toolbar-area select')?.disabled);
  assert.equal(await select.inputValue(), 'Teknaf, Cox\'s Bazar');
  assert.equal(await select.locator('optgroup').count(), 65);
  await filter.fill('Kaliganj');
  assert.ok(await select.locator('optgroup option').count() >= 4);
  await select.selectOption('Kaliganj, Satkhira');
  const pending = page.waitForRequest(request => request.url().includes('/rpc/search_available_properties'));
  await page.locator('.renter-toolbar-apply').click();
  const request = (await pending).postDataJSON();
  const chosen = locations.find(location => location.label === 'Kaliganj, Satkhira');
  assert.equal(request.center_lat, chosen.latitude);
  assert.equal(request.center_long, chosen.longitude);
  await page.waitForFunction(() => !document.querySelector('.renter-toolbar-area select')?.disabled);
  await filter.fill('unsupported neighborhood');
  assert.equal(await select.locator('optgroup option').count(), 0);
  assert.equal(await select.inputValue(), chosen.label, 'Filtering must preserve the selected center');
  await filter.fill('');
  assert.equal(await select.locator('optgroup').count(), 65);
  await page.screenshot({ path: path.join(out, 'national-map-desktop.png') });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.getByRole('button', { name: 'Switch to Bangla', exact: true }).filter({ visible: true }).click();
  await page.waitForFunction(() => document.documentElement.lang === 'bn');
  await page.getByRole('searchbox', { name: 'এলাকার তালিকা ফিল্টার করুন' }).fill('কালীগঞ্জ');
  assert.ok((await select.locator('option:checked').textContent()).includes('সাতক্ষীরা'));
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole('button', { name: 'ফিল্টার', exact: true }).click();
  await page.getByRole('searchbox', { name: 'এলাকার তালিকা ফিল্টার করুন' }).fill('টেকনাফ');
  await select.selectOption('Teknaf, Cox\'s Bazar');
  assert.equal(await select.inputValue(), 'Teknaf, Cox\'s Bazar');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(out, 'national-map-mobile.png') });
  assert.deepEqual(errors, []);
  console.log('PASS national map picker: URL restore, district groups, filtering, duplicates, coordinates, selected-state preservation, Bangla and responsive layout');
} finally { await browser.close(); }
